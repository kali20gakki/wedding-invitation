def main():
    apply = '--apply' in sys.argv
    with open(SRC, encoding='utf-8') as handle:
        lines = handle.read().split('\n')

    bad = [i + 1 for i, line in enumerate(lines) if any(ord(c) > 127 for c in line)]
    unknown = [n for n in bad if n not in FIX]
    print(f'含非 ASCII 的行: {len(bad)}')
    print(f'未提供修复文本的行: {unknown if unknown else "无"}')

    out = []
    for index, line in enumerate(lines, start=1):
        if index in FIX:
            out.append(FIX[index])
        elif any(ord(c) > 127 for c in line):
            # 保底：没提供修复文本的坏行，先原样留下以便发现
            out.append(line)
        else:
            out.append(line)

    text = '\n'.join(out)
    remaining = [i + 1 for i, line in enumerate(text.split('\n'))
                 if any(ord(c) > 127 for c in line)]
    print(f'修复后仍含非 ASCII 的行: {len(remaining)}（这些是正常的规则/注释）')
    # 抽检：确认关键中文注释已恢复
    for key in ['纸鹤场', '风铃按钮', '抽卡层', '整屏节奏微调', '结尾文案', '窄屏与减弱动效',
                '风之旅', '命名映射']:
        print(f'  {key}: {"OK" if key in text else "MISSING"}')

    if unknown:
        print('=> 有未覆盖的坏行，未写出')
        return 1
    if not apply:
        print('（预演模式，未写出。加 --apply 生效）')
        return 0

    shutil.copy(SRC, SRC + '.bak')
    with open(SRC, 'w', encoding='utf-8', newline='') as handle:
        handle.write(text)
    print(f'已修复并写出 {SRC}（备份 {SRC}.bak）')
    return 0


if __name__ == '__main__':
    sys.exit(main())
